import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import test from "node:test";

const facts = JSON.parse(readFileSync(fileURLToPath(new URL("../app/facts.json", import.meta.url)), "utf8"));

async function render() {
  const workerUrl = new URL("../dist/server/index.js", import.meta.url);
  workerUrl.searchParams.set("test", `${process.pid}-${Date.now()}`);
  const { default: worker } = await import(workerUrl.href);

  return worker.fetch(
    new Request("http://localhost/", { headers: { accept: "text/html" } }),
    { ASSETS: { fetch: async () => new Response("Not found", { status: 404 }) } },
    { waitUntil() {}, passThroughOnException() {} },
  );
}

test("server-renders the complete Zimlo work report", async () => {
  const response = await render();
  assert.equal(response.status, 200);
  assert.match(response.headers.get("content-type") ?? "", /^text\/html\b/i);

  const html = await response.text();
  assert.match(html, /<html[^>]+lang="zh-CN"/i);
  assert.match(html, /<title>Zimlo — 移动端 Coding Agent 注意力系统<\/title>/i);
  assert.match(html, /把 Coding Agent/);
  assert.match(html, /Project Agent/);
  // Evidence numbers come from app/facts.json, generated by scripts/generate-facts.mjs.
  assert.ok(html.includes(`<strong>${facts.testCases}</strong>`), "test case count from facts.json");
  // React inserts `<!-- -->` between adjacent text nodes during SSR.
  assert.match(html, new RegExp(`${facts.testFiles}(?:<!-- -->)? 个测试文件`), "test file count from facts.json");
  assert.ok(html.includes(facts.commit), "current commit hash from facts.json");
  if (facts.commitBaseUrl && !facts.dirty) {
    assert.ok(html.includes(`href="${facts.commitBaseUrl}${facts.commit}"`), "commit link from facts.json");
  }
  if (facts.commitBaseUrl) assert.ok(html.includes(`href="${facts.commitBaseUrl}0631957"`), "milestone commit link");
  assert.match(html, /0631957/);
  assert.match(html, /左滑/);
  assert.match(html, /og\.jpg/);
  assert.doesNotMatch(html, /Your site is taking shape|Building your site/);
});

import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repositoryRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const configuration = JSON.parse(
  await readFile(resolve(repositoryRoot, "config/zimlo-contract.json"), "utf8"),
);

if (
  typeof configuration.productVersion !== "string"
  || !/^\d+\.\d+\.\d+(?:[-+][0-9A-Za-z.-]+)?$/.test(configuration.productVersion)
  || !Number.isInteger(configuration.protocolVersion)
  || configuration.protocolVersion < 1
) {
  throw new Error("config/zimlo-contract.json contains an invalid product or protocol version");
}

const generatedHeader = "// Generated by scripts/generate-contract.mjs. Do not edit by hand.\n";
const outputs = new Map([
  [
    "apps/cli/src/version.ts",
    `${generatedHeader}export const ZIMLO_VERSION = ${JSON.stringify(configuration.productVersion)};\nexport const ZIMLO_PROTOCOL_VERSION = ${configuration.protocolVersion};\n`,
  ],
  [
    "apps/cloud/src/contract.generated.ts",
    `${generatedHeader}export const ZIMLO_PROTOCOL_VERSION = ${configuration.protocolVersion};\n`,
  ],
  [
    "apps/ios/Zimlo/ZimloContract.generated.swift",
    `${generatedHeader}enum ZimloContract {\n    static let productVersion = ${JSON.stringify(configuration.productVersion)}\n    static let protocolVersion = ${configuration.protocolVersion}\n}\n`,
  ],
  [
    "apps/macos/Sources/ZimloMac/ZimloContract.generated.swift",
    `${generatedHeader}enum ZimloContract {\n    static let productVersion = ${JSON.stringify(configuration.productVersion)}\n    static let protocolVersion = ${configuration.protocolVersion}\n}\n`,
  ],
]);

const checkOnly = process.argv.includes("--check");
const mismatches = [];

for (const [relativePath, expected] of outputs) {
  const absolutePath = resolve(repositoryRoot, relativePath);
  if (checkOnly) {
    const actual = await readFile(absolutePath, "utf8").catch(() => null);
    if (actual !== expected) mismatches.push(relativePath);
    continue;
  }
  await mkdir(dirname(absolutePath), { recursive: true });
  await writeFile(absolutePath, expected);
}

if (mismatches.length > 0) {
  console.error(`Generated contract files are stale:\n${mismatches.map((path) => `- ${path}`).join("\n")}`);
  console.error("Run: pnpm contract:generate");
  process.exitCode = 1;
}

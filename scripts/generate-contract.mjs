import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repositoryRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const configuration = JSON.parse(
  await readFile(resolve(repositoryRoot, "config/zimlo-contract.json"), "utf8"),
);
const cardSystem = JSON.parse(
  await readFile(resolve(repositoryRoot, "config/card-system.json"), "utf8"),
);

if (
  typeof configuration.productVersion !== "string"
  || !/^\d+\.\d+\.\d+(?:[-+][0-9A-Za-z.-]+)?$/.test(configuration.productVersion)
  || !Number.isInteger(configuration.protocolVersion)
  || configuration.protocolVersion < 1
) {
  throw new Error("config/zimlo-contract.json contains an invalid product or protocol version");
}

const cardLists = ["systems", "themes", "layouts", "typography", "densities", "mediaPlacements"];
if (cardSystem.schemaVersion !== 1 || cardLists.some((key) => !Array.isArray(cardSystem[key]) || cardSystem[key].length === 0)) {
  throw new Error("config/card-system.json contains an invalid card catalog");
}
for (const key of cardLists) {
  const ids = cardSystem[key].map((item) => item.id);
  if (ids.some((id) => typeof id !== "string" || !/^[a-z][a-z0-9_]*$/u.test(id)) || new Set(ids).size !== ids.length) {
    throw new Error(`config/card-system.json contains invalid or duplicate ${key} ids`);
  }
}
const systems = new Set(cardSystem.systems.map((item) => item.id));
if ([...cardSystem.themes, ...cardSystem.layouts].some((item) => !systems.has(item.system))) {
  throw new Error("config/card-system.json references an unknown visual system");
}
if (cardSystem.themes.some((theme) => [theme.ink, theme.surface, theme.accent].some((color) => !/^#[0-9A-F]{6}$/u.test(color)))) {
  throw new Error("config/card-system.json contains an invalid theme color");
}
const layoutRequirements = new Set(["media", "document", "attention", "quote", "metric", "comparison", "step"]);
if (cardSystem.layouts.some((layout) => !Array.isArray(layout.requires) || layout.requires.some((requirement) => !layoutRequirements.has(requirement)))) {
  throw new Error("config/card-system.json contains an invalid layout requirement");
}

const generatedHeader = "// Generated by scripts/generate-contract.mjs. Do not edit by hand.\n";
const js = (value) => JSON.stringify(value, null, 2);
const tuple = (items) => items.map((item) => JSON.stringify(item.id)).join(", ");
const swiftStringArray = (items) => items.map((item) => JSON.stringify(item.id)).join(", ");
const swiftDictionary = (items, value) => items.map((item) => `        ${JSON.stringify(item.id)}: ${value(item)}`).join(",\n");

const generatedCardSystemTS = `${generatedHeader}
export const CARD_SYSTEMS = [${tuple(cardSystem.systems)}] as const;
export const CARD_THEMES = [${tuple(cardSystem.themes)}] as const;
export const CARD_LAYOUTS = [${tuple(cardSystem.layouts)}] as const;
export const CARD_TYPOGRAPHY = [${tuple(cardSystem.typography)}] as const;
export const CARD_DENSITIES = [${tuple(cardSystem.densities)}] as const;
export const CARD_MEDIA_PLACEMENTS = [${tuple(cardSystem.mediaPlacements)}] as const;
export const CARD_CATALOG = ${js(cardSystem)} as const;
`;

const generatedCardSystemSwift = `${generatedHeader}enum ZimloContract {
    static let productVersion = ${JSON.stringify(configuration.productVersion)}
    static let protocolVersion = ${configuration.protocolVersion}
}

enum ZimloCardCatalog {
    static let systems = [${swiftStringArray(cardSystem.systems)}]
    static let themes = [${swiftStringArray(cardSystem.themes)}]
    static let layouts = [${swiftStringArray(cardSystem.layouts)}]
    static let typography = [${swiftStringArray(cardSystem.typography)}]
    static let densities = [${swiftStringArray(cardSystem.densities)}]
    static let mediaPlacements = [${swiftStringArray(cardSystem.mediaPlacements)}]
    static let themeSystems: [String: String] = [
${swiftDictionary(cardSystem.themes, (item) => JSON.stringify(item.system))}
    ]
    static let layoutSystems: [String: String] = [
${swiftDictionary(cardSystem.layouts, (item) => JSON.stringify(item.system))}
    ]
    static let themeInk: [String: String] = [
${swiftDictionary(cardSystem.themes, (item) => JSON.stringify(item.ink))}
    ]
    static let themeSurface: [String: String] = [
${swiftDictionary(cardSystem.themes, (item) => JSON.stringify(item.surface))}
    ]
    static let themeAccent: [String: String] = [
${swiftDictionary(cardSystem.themes, (item) => JSON.stringify(item.accent))}
    ]
}
`;

const generatedCardSystemCSS = `/* Generated by scripts/generate-contract.mjs. Do not edit by hand. */\n${cardSystem.themes.map((theme) => `.card-theme-${theme.id} { --card-ink: ${theme.ink}; --card-surface: ${theme.surface}; --card-accent: ${theme.accent}; }`).join("\n")}\n`;

const outputs = new Map([
  [
    "apps/cli/src/version.ts",
    `${generatedHeader}export const ZIMLO_VERSION = ${JSON.stringify(configuration.productVersion)};\nexport const ZIMLO_PROTOCOL_VERSION = ${configuration.protocolVersion};\n`,
  ],
  [
    "apps/cloud/src/contract.generated.ts",
    `${generatedHeader}export const ZIMLO_PROTOCOL_VERSION = ${configuration.protocolVersion};\n`,
  ],
  [
    "apps/ios/Zimlo/ZimloContract.generated.swift",
    generatedCardSystemSwift,
  ],
  [
    "apps/macos/Sources/ZimloMac/ZimloContract.generated.swift",
    generatedCardSystemSwift,
  ],
  ["packages/protocol/src/card-system.generated.ts", generatedCardSystemTS],
  ["apps/web/src/card-system.generated.css", generatedCardSystemCSS],
]);

const checkOnly = process.argv.includes("--check");
const mismatches = [];

for (const [relativePath, expected] of outputs) {
  const absolutePath = resolve(repositoryRoot, relativePath);
  if (checkOnly) {
    const actual = await readFile(absolutePath, "utf8").catch(() => null);
    if (actual !== expected) mismatches.push(relativePath);
    continue;
  }
  await mkdir(dirname(absolutePath), { recursive: true });
  await writeFile(absolutePath, expected);
}

if (mismatches.length > 0) {
  console.error(`Generated contract files are stale:\n${mismatches.map((path) => `- ${path}`).join("\n")}`);
  console.error("Run: pnpm contract:generate");
  process.exitCode = 1;
}

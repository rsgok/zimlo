import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repositoryRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const sourcePath = "apps/cli/src/store-schema.ts";
const outputPath = "runtime/crates/zimlo-store/src/bootstrap.sql";
const source = await readFile(resolve(repositoryRoot, sourcePath), "utf8");
const marker = "database.exec(`";
const start = source.indexOf(marker);
const end = start < 0 ? -1 : source.indexOf("`);", start + marker.length);

if (start < 0 || end < 0) {
  throw new Error(`Unable to extract the bootstrap schema from ${sourcePath}`);
}

const sql = source.slice(start + marker.length, end).trim();
const expected = `-- Generated by scripts/generate-runtime-schema.mjs from ${sourcePath}.\n-- Do not edit by hand while Node remains the schema authority.\n${sql}\n`;
const absoluteOutput = resolve(repositoryRoot, outputPath);

if (process.argv.includes("--check")) {
  const actual = await readFile(absoluteOutput, "utf8").catch(() => null);
  if (actual !== expected) {
    console.error(`Generated Runtime schema is stale:\n- ${outputPath}`);
    console.error("Run: pnpm runtime:schema:generate");
    process.exitCode = 1;
  }
} else {
  await mkdir(dirname(absoluteOutput), { recursive: true });
  await writeFile(absoluteOutput, expected);
}
